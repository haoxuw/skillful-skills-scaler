"""Part 4: generated skills.

Unpatched skills are copied deterministically. Patched skills are produced by the
agent: `plan` hands it everything it needs, `finalize` validates and stamps the
result, `conflict` records that a patch no longer applies."""
from __future__ import annotations

import json
import shutil
import tempfile
from pathlib import Path

from . import frontmatter, gitutil, patches as patchmod
from .manifest import Manifest, ManifestError, Skill, now_iso
from .status import provenance


def _copy_tree(src: Path, dst: Path) -> None:
    if dst.exists() or dst.is_symlink():
        if dst.is_symlink():
            dst.unlink()
        else:
            shutil.rmtree(dst)
    shutil.copytree(src, dst, symlinks=False)


def _stamp(m: Manifest, skill: Skill, out_dir: Path, model: str | None = None) -> dict:
    src = m.source(skill.source)
    meta, body = frontmatter.read(out_dir / "SKILL.md")
    if not frontmatter.is_valid(meta):
        raise ManifestError(
            f"{skill.name}: SKILL.md front matter is not valid YAML ({meta['_frontmatter_error']}). "
            "Fix it in a patch (or upstream) before generating; SSS will not write a damaged skill.")
    meta["name"] = skill.name
    metadata = meta.get("metadata") if isinstance(meta.get("metadata"), dict) else {}
    prov = {
        "source": src.name,
        "source_commit": src.synced_commit or gitutil.head(m.root / src.path) or "unknown",
        "source_path": m.source_skill_rel(skill),
        "patches": list(skill.patches),
        "generated_at": now_iso(),
        "note": "Generated by SSS. Do not edit. Change the patch or the source instead.",
    }
    if model:
        prov["model"] = model
    metadata["sss"] = prov
    meta["metadata"] = metadata
    frontmatter.write(out_dir / "SKILL.md", meta, body)
    skill.generated_at = prov["generated_at"]
    skill.status = "ok"
    skill.conflict = None
    m.save()
    return prov


def copy(m: Manifest, skill: Skill) -> dict:
    if skill.patches:
        raise ManifestError(f"{skill.name} has patches; use plan + finalize")
    src_dir = m.root / m.source_skill_rel(skill)
    if not (src_dir / "SKILL.md").is_file():
        raise ManifestError(f"source skill not found: {m.source_skill_rel(skill)}")
    out_dir = m.root / m.output_rel(skill)
    _copy_tree(src_dir, out_dir)
    try:
        prov = _stamp(m, skill, out_dir)
    except ManifestError:
        shutil.rmtree(out_dir, ignore_errors=True)   # never leave a half-made skill behind
        raise
    return {"skill": skill.name, "action": "copied", "output": m.output_rel(skill), "provenance": prov}


def plan(m: Manifest, skill: Skill) -> dict:
    """Everything the agent needs to apply the patches. Pure read, no writes to the repo."""
    src = m.source(skill.source)
    src_rel = m.source_skill_rel(skill)
    out_rel = m.output_rel(skill)
    out_dir = m.root / out_rel
    loaded = [patchmod.load(m.root, p) for p in skill.patches]
    for p in loaded:
        if p.target and p.target != skill.name:
            raise ManifestError(f"patch {p.path} targets {p.target!r}, not {skill.name!r}")
        bad = patchmod.validate(p.checks)
        if bad:
            raise ManifestError(f"patch {p.path} has malformed checks: " + "; ".join(bad))

    prev = provenance(m, skill)
    previous_source_dir = None
    if prev.get("source_commit") and src.mode != "local":
        tmp = Path(tempfile.mkdtemp(prefix=f"sss-prev-{skill.name}-"))
        try:
            if src.mode == "submodule":
                gitutil.export_tree(m.root / src.path, prev["source_commit"], _inside(src, skill), tmp)
            else:
                last = gitutil.last_commit_touching(m.root, [out_rel])
                if last:
                    gitutil.export_tree(m.root, last, src_rel, tmp)
            previous_source_dir = str(tmp) if any(tmp.iterdir()) else None
        except Exception:  # best effort; the agent can work without it
            previous_source_dir = None

    return {
        "skill": skill.name,
        "source": {"name": src.name, "dir": src_rel, "commit": src.synced_commit},
        "output": out_rel,
        "previous_output_exists": (out_dir / "SKILL.md").is_file(),
        "previous_source_dir": previous_source_dir,
        "patches": [p.to_dict() for p in loaded],
        "sentence_checks": [c for p in loaded for c in p.sentence_checks],
        "deterministic_checks": [c for p in loaded for c in p.deterministic_checks],
        "instructions": [
            f"Read every file under {src_rel}. That is the new source, letter for letter.",
            "Read each patch body and intent. Apply them to the source with the smallest edits that satisfy the intent. Keep everything the patches do not mention exactly as the source has it.",
            "If previous_output_exists and previous_source_dir is set, diff previous source against previous output to see the edits made last time, and re-apply those same edits to the new source. Fall back to the patch intent only where the old edit no longer fits.",
            "If the source no longer contains what a patch assumes (for example the thing it edits was removed upstream), do NOT guess. Run: sss conflict <skill> --reason '<what no longer applies>' and stop.",
            f"Write the result to {out_rel}/ (SKILL.md plus any other files from the source). Keep the front matter; SSS will set name and provenance.",
            "Then verify each sentence_check against what you wrote. If any fails, fix the output or record a conflict.",
            f"Finally run: sss finalize {skill.name} [--model <model id you used>]",
        ],
    }


def finalize(m: Manifest, skill: Skill, model: str | None = None) -> dict:
    out_dir = m.root / m.output_rel(skill)
    if not (out_dir / "SKILL.md").is_file():
        raise ManifestError(f"nothing to finalize: {m.output_rel(skill)}/SKILL.md is missing")
    loaded = [patchmod.load(m.root, p) for p in skill.patches]
    det = [c for p in loaded for c in p.deterministic_checks]
    failures = patchmod.run_deterministic(out_dir, det)
    if failures:
        skill.status = "failed"
        m.save()
        return {"skill": skill.name, "action": "failed", "failures": failures}
    prov = _stamp(m, skill, out_dir, model=model)
    return {"skill": skill.name, "action": "finalized", "output": m.output_rel(skill),
            "sentence_checks_for_record": [c for p in loaded for c in p.sentence_checks], "provenance": prov}


def conflict(m: Manifest, skill: Skill, reason: str) -> dict:
    skill.status = "conflict"
    skill.conflict = {"reason": reason, "recorded_at": now_iso(),
                      "source_commit": m.source(skill.source).synced_commit}
    m.save()
    return {"skill": skill.name, "action": "conflict", "conflict": skill.conflict}


def _inside(src, skill: Skill) -> str:
    root = src.skills_root.strip("/")
    return f"{root}/{skill.skill_dir}" if root and root != "." else skill.skill_dir


def dumps(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False)
